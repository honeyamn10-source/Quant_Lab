"""Quant Lab — an open quantitative research and strategy-falsification platform.

The package is organized around the falsification loop:

    Hypothesis -> Evidence -> Attempt to falsify -> Measure uncertainty
    -> Document failures -> Reproduce
"""

__version__ = "0.1.0"

MISSION = (
    "Find trading hypotheses, test them honestly, attempt to destroy them "
    "statistically, simulate realistic execution, measure uncertainty, "
    "document failures, and only allow strategies with strong evidence to "
    "progress toward paper/live testing."
)

TAGLINE = "Don't prove your strategy works. Try to prove it doesn't."
